"""Generate Unicode 17 lettering data from an official UCD directory (argument 1)."""
import json,re,sys,unicodedata
from pathlib import Path
source=Path(sys.argv[1]);target=Path('src/lettering/vendor/bidi/data')
def source_file(name):
    direct=source/name
    return direct if direct.exists() else source/'extracted'/name
assert 'DerivedBidiClass-17.0.0' in source_file('DerivedBidiClass.txt').read_text().splitlines()[0], 'Use Unicode 17.0.0 inputs.'
def rows(name):
    for line in source_file(name).read_text().splitlines():
        line=line.split('#')[0].strip()
        if line:yield [s.strip() for s in line.split(';')]
def bounds(value):
    parts=value.split('..');return int(parts[0],16),int(parts[-1],16)
def b36(n):
    if n<0:return '-'+b36(-n)
    out=''
    while n:out='0123456789abcdefghijklmnopqrstuvwxyz'[n%36]+out;n//=36
    return out or '0'
def pairs(items):
    prev=0;out=[]
    for a,b in sorted(items):out.append(b36(a-prev)+'>'+b36(b-a));prev=b
    return ','.join(out)
aliases={};scripts={}
for row in rows('PropertyValueAliases.txt'):
    if row[0]=='bc':
        for alias in row[1:]:aliases[alias]=row[1]
    if row[0]=='sc':
        for alias in row[1:]:scripts[alias]=row[1]
classes=['L']*0x110000
for line in source_file('DerivedBidiClass.txt').read_text().splitlines():
    m=re.search(r'@missing: ([0-9A-F.]+); (\w+)',line)
    if m:
        a,b=bounds(m[1]);classes[a:b+1]=[aliases[m[2]]]*(b-a+1)
for row in rows('DerivedBidiClass.txt'):
    a,b=bounds(row[0]);classes[a:b+1]=[aliases[row[1]]]*(b-a+1)
encoded={}
for key in ['R','EN','ES','ET','AN','CS','B','S','WS','ON','BN','NSM','AL','LRO','RLO','LRE','RLE','PDF','LRI','RLI','FSI','PDI']:
    ranges=[];a=0
    while a<len(classes):
        if classes[a]!=key:a+=1;continue
        b=a
        while b+1<len(classes) and classes[b+1]==key:b+=1
        ranges.append((a,b));a=b+1
    prev=0;parts=[]
    for a,b in ranges:parts.append(b36(a-prev)+(('+'+b36(b-a))if b>a else ''));prev=b
    encoded[key]=','.join(parts)
(target/'bidiCharTypes.data.js').write_text('// Unicode 17.0.0; generated by scripts/generate-lettering-unicode.py. See UNICODE-LICENSE.txt.\nexport default '+json.dumps(encoded,indent=2)+'\n')
brackets=[];canonical=[]
for row in rows('BidiBrackets.txt'):
    a,b=int(row[0],16),int(row[1],16)
    if row[2]=='o':brackets.append((a,b))
    n=unicodedata.normalize('NFD',chr(a))
    if len(n)==1 and ord(n)!=a:canonical.append((a,ord(n)))
(target/'bidiBrackets.data.js').write_text('// Unicode 17.0.0; generated. See UNICODE-LICENSE.txt.\nexport default '+json.dumps({'pairs':pairs(brackets),'canonical':pairs(canonical)},indent=2)+'\n')
if True:  # Mirroring data is a required Unicode 17 input.
    mirrors=[(int(row[0],16),int(row[1],16))for row in rows('BidiMirroring.txt')]
    (target/'bidiMirroring.data.js').write_text('// Unicode 17.0.0; generated. See UNICODE-LICENSE.txt.\nexport default '+json.dumps(pairs(mirrors))+'\n')
script_ranges=sorted([[*bounds(row[0]),scripts[row[1]]]for row in rows('Scripts.txt')])
extensions=sorted([[*bounds(row[0]),row[1].split()]for row in rows('ScriptExtensions.txt')])
Path('src/lettering/unicode17.json').write_text(json.dumps({'version':'17.0.0','scripts':script_ranges,'extensions':extensions},separators=(',',':'))+'\n')
print(len(script_ranges),'script ranges;',len(extensions),'extension ranges')

# Deterministic representative subset for the ordinary test suite; full files stay external.
if (source/'BidiCharacterTest.txt').exists():
    cases=[];index=0
    for line in (source/'BidiCharacterTest.txt').read_text().splitlines():
        line=line.split('#')[0].strip()
        if not line:continue
        if index%191==0:
            codes,direction,base,levels,order=[s.strip()for s in line.split(';')]
            cases.append({'codes':[int(v,16)for v in codes.split()],'direction':['ltr','rtl','auto'][int(direction)],'base':int(base),'levels':[None if v=='x'else int(v)for v in levels.split()],'order':[int(v)for v in order.split()]})
        index+=1
    Path('tests/fixtures/bidi/unicode17.json').write_text(json.dumps(cases,separators=(',',':'))+'\n')
